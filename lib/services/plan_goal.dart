/// เป้าหมายของแพลนอาหาร (ลดน้ำหนัก / รักษาน้ำหนัก / เพิ่มกล้ามเนื้อ)
///
/// ใช้เรียงเมนูที่หยิบจากแพลนเก่าและคลังสูตรกลาง: เมนูที่อยู่ในช่วงเป้าต่อมื้อ
/// เหมือนกัน ให้เลือกเมนูที่เหมาะกับเป้าหมายก่อน (ไม่เปลี่ยนเป้าแคลอรี/โปรตีน
/// ที่ใช้วางแพลน และไม่เพิ่มคอลัมน์ในฐานข้อมูล — คิดจากแคลอรี/โปรตีนของเมนูที่มีอยู่)
class PlanGoal {
  PlanGoal._(); // ห้ามสร้างตัวแปรจากคลาสนี้ ใช้แค่ค่าคงที่/ฟังก์ชันข้างใน

  // ชื่อเป้าหมาย 3 แบบ (ข้อความนี้ถูกบันทึกลงฐานข้อมูลด้วย ถ้าแก้ต้องแก้ข้อมูลเก่าตาม)
  static const loseWeight = 'ลดน้ำหนัก';
  static const maintain = 'รักษาน้ำหนัก';
  static const gainMuscle = 'เพิ่มกล้ามเนื้อ';

  /// กติกาเพิ่มเติมสำหรับ prompt ของ Gemini ตามเป้าหมาย — ปริมาณคุมด้วยเป้า
  /// แคลอรี/โปรตีนที่ผู้ใช้กรอกอยู่แล้ว ส่วนนี้คุม "ลักษณะเมนู" ให้ตรงเป้าหมาย
  static String promptRule(String? goal) => switch (goal) {
    // เป้าลดน้ำหนัก -> บอก AI ให้เลือกเมนูไขมันต่ำ ผักเยอะ
    loseWeight =>
      'เน้นเมนูอิ่มนานแต่พลังงานไม่สูง: โปรตีนไม่ติดมัน ผักเยอะ '
          'เลี่ยงของทอด กะทิ และน้ำตาลเยอะ ใช้วิธีต้ม นึ่ง ย่าง ผัดน้ำมันน้อย',
    // เป้าเพิ่มกล้าม -> บอก AI ให้เน้นโปรตีน
    gainMuscle =>
      'เน้นโปรตีนสูงทุกมื้อ (เนื้อสัตว์ ไข่ เต้าหู้ ถั่ว) '
          'คู่กับคาร์โบไฮเดรตพอเหมาะ เช่น ข้าว เส้น เพื่อให้พลังงานพอ',
    // อย่างอื่น (รักษาน้ำหนัก/ไม่ระบุ) -> เมนูสมดุล
    _ => 'เน้นเมนูสมดุล มีทั้งโปรตีน คาร์โบไฮเดรต และผัก ในสัดส่วนพอดี',
  };

  /// คะแนนความเหมาะกับเป้าหมาย (มากกว่า = เลือกก่อน)
  /// - ลดน้ำหนัก: โปรตีนต่อแคลอรีสูง (อิ่มนาน พลังงานไม่เกิน)
  /// - เพิ่มกล้ามเนื้อ: โปรตีนสูง
  /// - รักษาน้ำหนัก / ไม่รู้เป้าหมาย: เท่ากันหมด (คงลำดับเดิม)
  static double score(String? goal, num calories, num protein) =>
      switch (goal) {
        loseWeight => calories > 0 ? protein / calories : 0, // หารโปรตีนด้วยแคลอรี (กันหารด้วย 0)
        gainMuscle => protein.toDouble(), // ใช้ปริมาณโปรตีนตรงๆ
        _ => 0, // ไม่ให้คะแนน
      };
}
