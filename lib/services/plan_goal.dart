/// เป้าหมายของแพลนอาหาร (ลดน้ำหนัก / รักษาน้ำหนัก / เพิ่มกล้ามเนื้อ)
///
/// ใช้เรียงเมนูที่หยิบจากแพลนเก่าและคลังสูตรกลาง: เมนูที่อยู่ในช่วงเป้าต่อมื้อ
/// เหมือนกัน ให้เลือกเมนูที่เหมาะกับเป้าหมายก่อน (ไม่เปลี่ยนเป้าแคลอรี/โปรตีน
/// ที่ใช้วางแพลน และไม่เพิ่มคอลัมน์ในฐานข้อมูล — คิดจากแคลอรี/โปรตีนของเมนูที่มีอยู่)
class PlanGoal {
  PlanGoal._();

  static const loseWeight = 'ลดน้ำหนัก';
  static const maintain = 'รักษาน้ำหนัก';
  static const gainMuscle = 'เพิ่มกล้ามเนื้อ';

  /// คะแนนความเหมาะกับเป้าหมาย (มากกว่า = เลือกก่อน)
  /// - ลดน้ำหนัก: โปรตีนต่อแคลอรีสูง (อิ่มนาน พลังงานไม่เกิน)
  /// - เพิ่มกล้ามเนื้อ: โปรตีนสูง
  /// - รักษาน้ำหนัก / ไม่รู้เป้าหมาย: เท่ากันหมด (คงลำดับเดิม)
  static double score(String? goal, num calories, num protein) =>
      switch (goal) {
        loseWeight => calories > 0 ? protein / calories : 0,
        gainMuscle => protein.toDouble(),
        _ => 0,
      };
}
