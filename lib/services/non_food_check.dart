/// ของในตู้เย็นที่ไม่ใช่วัตถุดิบทำอาหาร: บุหรี่/ยาสูบ และสุราสำหรับดื่ม
///
/// ใช้กรองรายการวัตถุดิบ "ก่อน" ส่งให้ Gemini สร้างเมนู/แพลน และก่อนจับคู่เมนูจาก
/// คลังสูตรกลาง — ตรวจจากชื่อปัจจุบันของวัตถุดิบทุกครั้ง ผู้ใช้แก้ชื่อทีหลัง
/// (เช่น AI อ่านขวดเหล้าเป็น "ซอส" แล้วแก้เป็น "เหล้าขาว") ก็ถูกตรวจตามชื่อใหม่
/// ไม่พึ่งคำสั่งใน prompt อย่างเดียว
///
/// สุราสำหรับปรุงอาหาร (เหล้าจีน ไวน์ปรุงอาหาร มิริน ฯลฯ) ยังใช้เป็นเครื่องปรุงได้
/// ข้อจำกัด: ตรวจจากชื่อเท่านั้น ถ้าตั้งชื่อไม่ตรงกับของจริง ระบบตรวจไม่ได้
class NonFoodCheck {
  NonFoodCheck._();

  /// สุราที่ใช้เป็นเครื่องปรุงอาหาร — ตรวจก่อนคำต้องห้าม
  static const _cookingAlcohol = [
    'ปรุงอาหาร',
    'ทำอาหาร',
    'cooking',
    'เหล้าจีน',
    'ฮัวเตียว',
    'shaoxing',
    'มิริน',
    'mirin',
    // น้ำส้มสายชูหมักจากไวน์ (red wine vinegar) เป็นเครื่องปรุง
    'น้ำส้มสายชู',
    'vinegar',
  ];

  /// บุหรี่ ยาสูบ และสุราสำหรับดื่ม
  static const _blocked = [
    // ยาสูบ
    'บุหรี่',
    'ยาสูบ',
    'ยาเส้น',
    'ซิการ์',
    'cigarette',
    'cigar',
    'tobacco',
    'vape',
    // สุราสำหรับดื่ม
    'สุรา',
    'เหล้า',
    'เบียร์',
    'ไวน์',
    'วิสกี้',
    'วอดก้า',
    'บรั่นดี',
    'สาเก',
    'โซจู',
    'ยาดอง',
    'สาโท',
    'อุ',
    'ค็อกเทล',
    'แชมเปญ',
    'เตกีล่า',
    'ลิเคียว',
    'สปาย',
    'beer',
    'wine',
    'whisky',
    'whiskey',
    'vodka',
    'brandy',
    'sake',
    'soju',
    'cocktail',
    'champagne',
    'tequila',
    'liqueur',
    'gin',
    'rum',
  ];

  /// คำที่ต้องตรงทั้งชื่อ (ไม่งั้นไปชนคำอื่น เช่น "อุ" ใน "อุด้ง", "gin" ใน "ginger",
  /// "สุรา" ใน "หอยนางรมสุราษฎร์")
  static const _exactOnly = {'อุ', 'gin', 'rum', 'สปาย', 'สุรา'};

  /// ไม่ใช่วัตถุดิบทำอาหาร (ไม่ส่งให้ AI / ไม่ใช้จับคู่เมนู)
  static bool isNotForCooking(Object? name) {
    final n = (name ?? '').toString().toLowerCase().replaceAll(RegExp(r'\s+'), '');
    if (n.isEmpty) return false;
    if (_cookingAlcohol.any(n.contains)) return false;
    for (final w in _blocked) {
      if (_exactOnly.contains(w) ? n == w : n.contains(w)) return true;
    }
    return false;
  }
}
